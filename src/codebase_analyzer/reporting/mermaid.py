"""
Generates Mermaid architecture diagrams from the dependency graph.
"""

from pathlib import Path

from codebase_analyzer.core.model import AnalysisResult


def get_component_name(qname: str) -> str:
    """
    Groups a module into a higher-level component by taking up to the first 3 parts of its qualified name.
    Example: app.domains.user.service.admin -> app.domains.user
    """
    parts = qname.split(".")
    return ".".join(parts[:3])


def generate_mermaid_diagram(result: AnalysisResult, graph: dict[str, list[str]], output_path: str = "architecture.md") -> None:
    """
    Aggregates file-level dependencies into domain-level component dependencies
    and writes a Markdown file with a Mermaid graph.
    """
    edges: set[tuple[str, str]] = set()
    components: set[str] = set()
    
    # 1. Aggregate file dependencies into component dependencies
    for source, targets in graph.items():
        src_comp = get_component_name(source)
        components.add(src_comp)
        
        for t in targets:
            tgt_comp = get_component_name(t)
            components.add(tgt_comp)
            if src_comp != tgt_comp:
                edges.add((src_comp, tgt_comp))
                
    # 2. Build the Mermaid string
    lines = [
        "# Project Architecture",
        "",
        "This diagram was automatically generated by `codebase-analyzer`.",
        "",
        "```mermaid",
        "graph TD",
    ]
    
    # Define nodes with safe IDs (Mermaid doesn't like dots in node IDs without quoting)
    # We use underscores for IDs and the real name for the label
    node_id_map = {}
    for comp in sorted(components):
        safe_id = comp.replace(".", "_")
        node_id_map[comp] = safe_id
        lines.append(f'    {safe_id}["{comp}"]')
        
    lines.append("")
    
    # Define edges
    for src_comp, tgt_comp in sorted(edges):
        src_id = node_id_map[src_comp]
        tgt_id = node_id_map[tgt_comp]
        lines.append(f"    {src_id} --> {tgt_id}")
        
    lines.append("```")
    lines.append("")
    
    # Write to file
    out_file = Path(output_path)
    out_file.write_text("\n".join(lines), encoding="utf-8")
    print(f"Architecture diagram generated: {out_file.resolve()}")
